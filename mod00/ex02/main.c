#include <avr/io.h>

int	main()
{										// 13.2.3
	DDRB |= (1 << DDB0);				// Write 1
	DDRD &= ~(1 << DDD2);				// Read 0
	
	while (1)
	{
		if (PIND & (1 << PIND2))
			PORTB &= ~(1 << PORTB0);	// OFF 0
		else
			PORTB |= (1 << PORTB0);		// ON 1
	}

	return (0);
}
